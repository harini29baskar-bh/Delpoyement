import "dotenv/config";
import express from "express";
import cors from "cors";
import helmet from "helmet";
import cookieParser from "cookie-parser";
import rateLimit from "express-rate-limit";
import { connectDB } from "./config/db.js";
import api from "./routes/api.js";

const app=express();
app.use(helmet());
app.use(cors({origin:process.env.CLIENT_URL||"http://localhost:5173",credentials:true}));
app.use(express.json({limit:"1mb"}));
app.use(cookieParser());
app.use("/api/auth",rateLimit({windowMs:15*60*1000,max:30,standardHeaders:true,legacyHeaders:false,skip:(req)=>req.method === "GET" && req.path === "/me"}));
app.get("/api/health",(req,res)=>res.json({status:"ok",service:"V2 CodeZero API"}));
app.use("/api",api);
app.use((err,req,res,next)=>{console.error(err);res.status(500).json({message:"Internal server error"});});
const port=process.env.PORT||5000;
connectDB().then(()=>app.listen(port,()=>console.log(`API running on ${port}`))).catch(e=>{console.error(e);process.exit(1);});
